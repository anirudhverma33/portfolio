// Every quantitative or result statement on the site lives here, with the exact
// sentence it comes from. Pages reference claims by id through <Claim> and
// <ResultsTable>; nothing numeric is typed directly into page copy.

export type ClaimKind =
  | 'measured'
  | 'theoretical-bound'
  | 'algebraic-limit'
  | 'analytical'
  | 'simulated'
  | 'model'
  | 'projection';

