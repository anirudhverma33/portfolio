const byId = new Map<string, Claim>();
for (const c of list) {
  if (byId.has(c.id)) throw new Error(`Duplicate claim id: ${c.id}`);
  if (!c.source || !c.quote) throw new Error(`Claim ${c.id} is missing its source or quote`);
  byId.set(c.id, c);
}

export const claims = list;

/** Look up a claim. In production builds, unknown or unconfirmed claims fail the build. */
export function getClaim(id: string): Claim {
  const c = byId.get(id);
  if (!c) throw new Error(`Unknown claim id "${id}"`);
  if (c.status !== 'verified' && import.meta.env?.PROD) {
    throw new Error(`Claim "${id}" is not confirmed and cannot be published`);
  }
  if (c.kind === 'projection') {
    throw new Error(`Claim "${id}" is a projection; projections are not shown on the site`);
  }
  return c;
}
